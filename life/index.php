<?php

session_start();


/*
|--------------------------------------------------------------------------
| RESPONSE SETTINGS
|--------------------------------------------------------------------------
*/

header("Content-Type: application/json; charset=UTF-8");

header(
    "Cache-Control: no-store, no-cache, must-revalidate, max-age=0"
);

header("Pragma: no-cache");


/*
|--------------------------------------------------------------------------
| DATABASE
|--------------------------------------------------------------------------
|
| Replace these with your existing SkySQL details.
|
*/

$host = "serverless-eastus.sysp0000.db3.skysql.com";
$user = "dbpbf12883888";
$password = "nyy6hj6v0#s61c2fTw%i";
$database = "incentive";
$port = 4003;

/*
|--------------------------------------------------------------------------
| DATABASE CONNECTION
|--------------------------------------------------------------------------
*/

$conn = mysqli_init();


if (!$conn) {

    http_response_code(500);

    echo json_encode([
        "success" => false,
        "message" =>
            "Unable to initialise database connection."
    ]);

    exit;
}


/*
|--------------------------------------------------------------------------
| SSL
|--------------------------------------------------------------------------
*/

mysqli_ssl_set(
    $conn,
    NULL,
    NULL,
    NULL,
    NULL,
    NULL
);


/*
|--------------------------------------------------------------------------
| CONNECT
|--------------------------------------------------------------------------
*/

if (
    !mysqli_real_connect(
        $conn,
        $host,
        $user,
        $password,
        $database,
        $port,
        NULL,
        MYSQLI_CLIENT_SSL
    )
) {

    http_response_code(500);

    echo json_encode([
        "success" => false,
        "message" =>
            "Database connection failed."
    ]);

    exit;
}


/*
|--------------------------------------------------------------------------
| CHARACTER SET
|--------------------------------------------------------------------------
*/

$conn->set_charset("utf8mb4");


/*
|--------------------------------------------------------------------------
| READ REQUEST
|--------------------------------------------------------------------------
*/

$input = json_decode(
    file_get_contents("php://input"),
    true
);


/*
|--------------------------------------------------------------------------
| FALLBACK FOR FORM POST
|--------------------------------------------------------------------------
*/

if (!is_array($input)) {

    $input = $_POST;
}


/*
|--------------------------------------------------------------------------
| ACTION
|--------------------------------------------------------------------------
*/

$action =
    $input["action"] ?? "";


/*
|--------------------------------------------------------------------------
| LOGIN
|--------------------------------------------------------------------------
*/

if ($action === "login") {


    /*
    |--------------------------------------------------------------------------
    | GET SMC
    |--------------------------------------------------------------------------
    */

    $smc = trim(
        $input["smc"] ?? ""
    );


    /*
    |--------------------------------------------------------------------------
    | CHECK SMC
    |--------------------------------------------------------------------------
    */

    if ($smc === "") {

        http_response_code(400);

        echo json_encode([
            "success" => false,
            "message" =>
                "Sales Man Code is required."
        ]);

        $conn->close();

        exit;
    }


    /*
    |--------------------------------------------------------------------------
    | FIND STAFF
    |--------------------------------------------------------------------------
    */

    $sql = "

        SELECT
            staff_name,
            sales_man_code,
            outlet,
            role

        FROM staff_details

        WHERE sales_man_code = ?

        LIMIT 1

    ";


    /*
    |--------------------------------------------------------------------------
    | PREPARE
    |--------------------------------------------------------------------------
    */

    $stmt =
        $conn->prepare($sql);


    if (!$stmt) {

        http_response_code(500);

        echo json_encode([
            "success" => false,
            "message" =>
                "Unable to prepare login query."
        ]);

        $conn->close();

        exit;
    }


    /*
    |--------------------------------------------------------------------------
    | BIND SMC
    |--------------------------------------------------------------------------
    */

    $stmt->bind_param(
        "s",
        $smc
    );


    /*
    |--------------------------------------------------------------------------
    | EXECUTE
    |--------------------------------------------------------------------------
    */

    if (!$stmt->execute()) {

        http_response_code(500);

        echo json_encode([
            "success" => false,
            "message" =>
                "Unable to execute login query."
        ]);

        $stmt->close();

        $conn->close();

        exit;
    }


    /*
    |--------------------------------------------------------------------------
    | RESULT
    |--------------------------------------------------------------------------
    */

    $result =
        $stmt->get_result();


    /*
    |--------------------------------------------------------------------------
    | SMC NOT FOUND
    |--------------------------------------------------------------------------
    */

    if ($result->num_rows === 0) {

        http_response_code(401);

        echo json_encode([
            "success" => false,
            "message" =>
                "Invalid Sales Man Code."
        ]);

        $stmt->close();

        $conn->close();

        exit;
    }


    /*
    |--------------------------------------------------------------------------
    | GET STAFF
    |--------------------------------------------------------------------------
    */

    $staff =
        $result->fetch_assoc();


    /*
    |--------------------------------------------------------------------------
    | CLEAN ROLE
    |--------------------------------------------------------------------------
    */

    $role = strtolower(
        trim(
            $staff["role"] ?? ""
        )
    );


    /*
    |--------------------------------------------------------------------------
    | CHECK ROLE
    |--------------------------------------------------------------------------
    */

    if (
        $role !== "staff" &&
        $role !== "admin"
    ) {

        http_response_code(403);

        echo json_encode([
            "success" => false,
            "message" =>
                "This account does not have a valid role."
        ]);

        $stmt->close();

        $conn->close();

        exit;
    }


    /*
    |--------------------------------------------------------------------------
    | NEW SESSION ID
    |--------------------------------------------------------------------------
    */

    session_regenerate_id(true);


    /*
    |--------------------------------------------------------------------------
    | SAVE SESSION
    |--------------------------------------------------------------------------
    */

    $_SESSION["logged_in"] = true;

    $_SESSION["staff_name"] =
        $staff["staff_name"];

    $_SESSION["sales_man_code"] =
        $staff["sales_man_code"];

    $_SESSION["outlet"] =
        $staff["outlet"];

    $_SESSION["role"] =
        $role;


    /*
    |--------------------------------------------------------------------------
    | LOGIN SUCCESS
    |--------------------------------------------------------------------------
    */

    echo json_encode([

        "success" => true,

        "message" =>
            "Login successful.",

        "role" =>
            $role,

        "staff_name" =>
            $staff["staff_name"],

        "sales_man_code" =>
            $staff["sales_man_code"],

        "outlet" =>
            $staff["outlet"]

    ]);


    /*
    |--------------------------------------------------------------------------
    | CLOSE
    |--------------------------------------------------------------------------
    */

    $stmt->close();

    $conn->close();

    exit;
}


/*
|--------------------------------------------------------------------------
| LOGOUT
|--------------------------------------------------------------------------
*/

if ($action === "logout") {


    /*
    |--------------------------------------------------------------------------
    | CLEAR SESSION
    |--------------------------------------------------------------------------
    */

    $_SESSION = [];


    /*
    |--------------------------------------------------------------------------
    | REMOVE SESSION COOKIE
    |--------------------------------------------------------------------------
    */

    if (
        ini_get("session.use_cookies")
    ) {

        $params =
            session_get_cookie_params();


        setcookie(

            session_name(),

            "",

            time() - 42000,

            $params["path"],

            $params["domain"],

            $params["secure"],

            $params["httponly"]

        );
    }


    /*
    |--------------------------------------------------------------------------
    | DESTROY
    |--------------------------------------------------------------------------
    */

    session_destroy();


    /*
    |--------------------------------------------------------------------------
    | RESPONSE
    |--------------------------------------------------------------------------
    */

    echo json_encode([

        "success" => true,

        "message" =>
            "Logged out successfully."

    ]);


    $conn->close();

    exit;
}


/*
|--------------------------------------------------------------------------
| CHECK SESSION
|--------------------------------------------------------------------------
*/

if ($action === "check_session") {


    /*
    |--------------------------------------------------------------------------
    | LOGGED IN
    |--------------------------------------------------------------------------
    */

    if (
        isset($_SESSION["logged_in"]) &&
        $_SESSION["logged_in"] === true
    ) {

        echo json_encode([

            "success" => true,

            "logged_in" => true,

            "role" =>
                $_SESSION["role"] ?? "",

            "staff_name" =>
                $_SESSION["staff_name"] ?? "",

            "sales_man_code" =>
                $_SESSION["sales_man_code"] ?? "",

            "outlet" =>
                $_SESSION["outlet"] ?? ""

        ]);

    }


    /*
    |--------------------------------------------------------------------------
    | NOT LOGGED IN
    |--------------------------------------------------------------------------
    */

    else {

        echo json_encode([

            "success" => true,

            "logged_in" => false

        ]);
    }


    $conn->close();

    exit;
}


/*
|--------------------------------------------------------------------------
| INVALID ACTION
|--------------------------------------------------------------------------
*/

http_response_code(400);

echo json_encode([

    "success" => false,

    "message" =>
        "Invalid request."

]);


$conn->close();

?>
